import Foundation
import ReceiptKit
import ReceiptKitEvaluation
import ReceiptKitIntelligence

/// Compares receipt extractors on a folder of labeled fixtures.
///
///     swift run receiptkit-eval Eval/fixtures
///     swift run receiptkit-eval Eval/fixtures --extractor heuristic --verbose
///     swift run receiptkit-eval Eval/fixtures --output Eval/RESULTS.md
@main
struct ReceiptKitEval {
    static let usage = """
        Usage: receiptkit-eval [fixtures-dir] [options]

          fixtures-dir           Folder of fixture .json files (default: Eval/fixtures)
          --extractor <names>    Comma-separated: heuristic, foundation-models,
                                 foundation-models-ungrounded (default: first two)
          --output <file>        Also write the results table to a Markdown file
          --verbose, -v          Print what went wrong for each incorrect receipt
          --help, -h             Show this help
        """

    struct Options {
        var fixturesPath = "Eval/fixtures"
        var extractors = ["heuristic", "foundation-models"]
        var outputPath: String?
        var verbose = false
    }

    static func main() async {
        do {
            guard let options = try parse(Array(CommandLine.arguments.dropFirst())) else {
                print(usage)
                return
            }
            try await run(options)
        } catch {
            FileHandle.standardError.write(Data("error: \(error)\n\n\(usage)\n".utf8))
            exit(1)
        }
    }

    static func run(_ options: Options) async throws {
        let directory = URL(fileURLWithPath: options.fixturesPath)
        let fixtures = try FixtureFormat.loadFixtures(in: directory)
        guard !fixtures.isEmpty else {
            throw CLIError("No .json fixtures in \(directory.path)")
        }

        let drafts = fixtures.filter { $0.notes?.hasPrefix("DRAFT") == true }
        if !drafts.isEmpty {
            print("⚠️  \(drafts.count) fixture(s) still marked DRAFT. Verify their labels, then delete the note:")
            drafts.forEach { print("   - \($0.id)") }
            print()
        }

        print("Evaluating \(fixtures.count) receipts…\n")

        var reports: [EvaluationReport] = []
        for name in options.extractors {
            guard let extractor = makeExtractor(named: name) else { continue }
            let report = await ReceiptEvaluator.evaluate(extractor, named: name, on: fixtures, warmUp: true)
            reports.append(report)

            if options.verbose {
                print("── \(name) ──")
                print(ReportFormatter.failures(report, fixtures: fixtures))
                print()
            }
        }

        guard !reports.isEmpty else { throw CLIError("No extractor could run.") }

        let table = ReportFormatter.markdownTable(reports)
        print(table)

        if let outputPath = options.outputPath {
            let header = """
                # ReceiptKit evaluation

                Generated by `swift run receiptkit-eval` on \(Date().formatted(date: .abbreviated, time: .omitted)), \
                \(ProcessInfo.processInfo.operatingSystemVersionString). Latency is extraction only (OCR excluded), \
                measured on this Mac after one untimed warm-up run.


                """
            try (header + table + "\n").write(toFile: outputPath, atomically: true, encoding: .utf8)
            print("\nWrote \(outputPath)")
        }
    }

    static func makeExtractor(named name: String) -> (any ReceiptExtracting)? {
        switch name {
        case "heuristic":
            return HeuristicReceiptExtractor()

        case "foundation-models", "foundation-models-ungrounded":
            #if canImport(FoundationModels)
            if #available(macOS 26.0, iOS 26.0, *) {
                if let reason = FoundationModelsReceiptExtractor.unavailabilityReason {
                    print("Skipping \(name): model unavailable (\(reason)).")
                    print("Turn on Apple Intelligence in System Settings, then try again.\n")
                    return nil
                }
                return FoundationModelsReceiptExtractor(groundsAmounts: name == "foundation-models")
            }
            print("Skipping \(name): requires macOS 26 or later.\n")
            return nil
            #else
            print("Skipping \(name): built with an SDK without FoundationModels. Use Xcode 26 or later (check `swift --version`).\n")
            return nil
            #endif

        default:
            print("Skipping unknown extractor \"\(name)\".\n")
            return nil
        }
    }

    static func parse(_ arguments: [String]) throws -> Options? {
        var options = Options()
        var iterator = arguments.makeIterator()

        while let argument = iterator.next() {
            switch argument {
            case "--help", "-h":
                return nil
            case "--verbose", "-v":
                options.verbose = true
            case "--extractor":
                guard let value = iterator.next() else { throw CLIError("--extractor needs a value") }
                options.extractors = value.split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
            case "--output":
                guard let value = iterator.next() else { throw CLIError("--output needs a file path") }
                options.outputPath = value
            default:
                guard !argument.hasPrefix("-") else { throw CLIError("Unknown option \(argument)") }
                options.fixturesPath = argument
            }
        }
        return options
    }
}

struct CLIError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}
